"""Generates cardbridge/src/shape/ShapeBodyGenerated.inc (and the head one) from the decompiled
ShapeBodyInfoFemale / ShapeHeadInfoFemale classes of the game's Assembly-CSharp.dll.

The game turns a card's 44 body / 52 face slider values into bone scales, offsets and rotations with
a few hundred lines of straight-line formulas. They are copied here as generated C++ (the owner
allowed copying game code the converter needs) so CardBridge reproduces proportions without the game.

    python -I -X utf8 gen_shape.py <decompiled src folder> <output folder>

The input is the ilspycmd output of Assembly-CSharp.dll (a research artefact, not shipped).
"""
import re, sys, os

src_dir, out_dir = sys.argv[1], sys.argv[2]


def load(name):
    s = open(os.path.join(src_dir, name + '.cs'), encoding='utf-8').read()
    s = re.sub(r'\n\s*//IL_[^\n]*', '', s)
    s = re.sub(r'\n\s*\n', '\n', s)
    return s.splitlines()


def enum_names(lines, enum):
    i = next(k for k, l in enumerate(lines) if re.search(r'public enum %s\b' % enum, l))
    out = []
    for l in lines[i + 2:]:
        t = l.strip().rstrip(',')
        if t == '}':
            break
        out.append(t)
    return out


def method(lines, name):
    i = next(k for k, l in enumerate(lines) if 'public override void %s()' % name in l)
    depth = 0
    out = []
    started = False
    for l in lines[i + 1:]:
        out.append(l)
        depth += l.count('{') - l.count('}')
        if '{' in l:
            started = True
        if started and depth == 0:
            break
    return out


NUM = re.compile(r'(?<![\w.])(\d+)f\b')


def tr(line, cls):
    t = line.strip()
    if t in ('{', '}'):
        return t
    t = t.replace('((uint)updateMask & ', '(updateMask & ')
    t = t.replace('(true ? 1u : 0u)', '1u')
    t = re.sub(r'if \(!base\.InitEnd \|\| dictSrc\.Count == 0\)', 'if (!S.initEnd)', t)
    t = re.sub(r'if \(base\.InitEnd && dictSrc\.Count != 0\)', 'if (S.initEnd)', t)
    t = t.replace('BoneInfo value;', 'Bone* value = nullptr;')
    t = re.sub(r'if \(dictDst\.TryGetValue\((\d+), out value\)\)', r'if ((value = S.dst(\1)) != nullptr)', t)
    t = re.sub(r'if \(dictDst\.TryGetValue\((\d+), out var value\)\)', r'if (Bone* value = S.dst(\1))', t)
    t = re.sub(r'value\.trfBone\.SetLocalPosition([XYZ])\((.*)\);', lambda m: 'value->pos.%s = %s;' % (m.group(1).lower(), m.group(2)), t)
    t = re.sub(r'value\.trfBone\.SetLocalScale\((.*)\);', r'value->scl = {\1};', t)
    t = re.sub(r'value\.trfBone\.SetLocalRotation\((.*)\);', r'{ value->rot = {\1}; value->rotSet = true; }', t)
    t = re.sub(r'dictSrc\[(\d+)\]\.vctPos', r'S.src(\1).pos', t)
    t = re.sub(r'dictSrc\[(\d+)\]\.vctRot', r'S.src(\1).rot', t)
    t = re.sub(r'dictSrc\[(\d+)\]\.vctScl', r'S.src(\1).scl', t)
    t = re.sub(r'correctValue\[(\d+)\]\.vctPos', r'S.correct(\1).pos', t)
    t = re.sub(r'correctValue\[(\d+)\]\.vctRot', r'S.correct(\1).rot', t)
    t = re.sub(r'correctValue\[(\d+)\]\.vctScl', r'S.correct(\1).scl', t)
    t = t.replace('base.typeBone', 'S.typeBone')
    t = re.sub(r'(?<![\w.])correctHeadSize', 'S.correctHeadSize', t)
    t = re.sub(r'(?<![\w.])correctNeckSize', 'S.correctNeckSize', t)
    t = re.sub(r'(?<![\w.])headCorrectValue', 'S.headCorrectValue', t)
    t = t.replace('Transform parent = value.trfBone.parent;', 'Vec3 parentScale = S.parentLossyScale(value);')
    t = re.sub(r'parent\.lossyScale\.([xyz])', r'parentScale.\1', t)
    t = re.sub(r'if \(fixCorrectBone != null && fixCorrectBone\.Length == 2\)', 'if (true)', t)
    t = re.sub(r'if \(Object\.op_Implicit\(\(Object\)\(object\)fixCorrectBone\[(\d)\]\)\)', r'if (S.fixCorrect[\1])', t)
    t = re.sub(r'fixCorrectBone\[(\d)\]\.SetLocalPositionX\((\w+)\);', r'S.fixCorrect[\1]->pos.x = \2;', t)
    t = NUM.sub(r'\1.0f', t)
    t = t.replace('return;', 'return;')
    return t


def emit(cls, prefix, enums):
    lines = load(cls)
    out = ['// GENERATED by tools/gen_shape.py from the game\'s %s - do not edit by hand.' % cls,
           '// Source: decompiled Assembly-CSharp.dll (copied game logic, see tools/gen_shape.py).', '']
    for e, nm in enums:
        names = enum_names(lines, e)
        out.append('static const char* const %s[] = {' % nm)
        for i in range(0, len(names), 6):
            out.append('    ' + ', '.join('"%s"' % n for n in names[i:i + 6]) + ',')
        out.append('};')
        out.append('')
    for m in ('Update', 'UpdateAlways'):
        body = method(lines, m)
        sig = 'static void %s%s(ShapeState& S%s)' % (prefix, m, ', unsigned updateMask' if m == 'Update' and prefix == 'Body' else '')
        out.append(sig)
        declared = any('BoneInfo value;' in l for l in body)
        for k, l in enumerate(body):
            out.append('    ' + tr(l, cls))
            if k == 0 and not declared and any('out var value' in x for x in body):
                out.append('    Bone* value = nullptr;')
        out.append('')
    return '\n'.join(out) + '\n'


os.makedirs(out_dir, exist_ok=True)
open(os.path.join(out_dir, 'ShapeBodyGenerated.inc'), 'w', encoding='utf-8').write(
    emit('ShapeBodyInfoFemale', 'Body', [('DstName', 'kBodyDst'), ('SrcName', 'kBodySrc'), ('CorrectKeyName', 'kBodyCorrect')]))
open(os.path.join(out_dir, 'ShapeHeadGenerated.inc'), 'w', encoding='utf-8').write(
    emit('ShapeHeadInfoFemale', 'Head', [('DstBoneName', 'kHeadDst'), ('SrcBoneName', 'kHeadSrc')]))
print('generated')
